#!/bin/bash

# pH Install Script for macOS
# Installs the addon to your WoW Classic AddOns directory

set -e

echo "======================================"
echo "  pH Addon Installer (macOS)"
echo "======================================"
echo ""

# Define WoW Anniversary installation paths
WOW_PATHS=(
    "/Applications/World of Warcraft/_anniversary_/Interface/AddOns"
    "$HOME/Applications/World of Warcraft/_anniversary_/Interface/AddOns"
    "/Applications/World of Warcraft/_classic_beta_/Interface/Addons"
    "$HOME/Applications/World of Warcraft/_classic_beta_/Interface/Addons"
)

# Find existing WoW installations
FOUND_PATHS=()
for path in "${WOW_PATHS[@]}"; do
    if [ -d "$path" ]; then
        FOUND_PATHS+=("$path")
    fi
done

# Check if WoW Anniversary installation was found
if [ ${#FOUND_PATHS[@]} -eq 0 ]; then
    echo "❌ Error: Could not find WoW Classic Anniversary AddOns directory"
    echo ""
    echo "Searched in:"
    for path in "${WOW_PATHS[@]}"; do
        echo "  - $path"
    done
    echo ""
    echo "Please ensure WoW Classic Anniversary is installed or specify the path manually:"
    echo "  ./install.sh /path/to/WoW/_anniversary_/Interface/AddOns"
    exit 1
fi

# Install to the path given by the user, otherwise to every found install
# (Anniversary and/or Forever beta)
if [ -n "$1" ]; then
    if [ ! -d "$1" ]; then
        echo "❌ Error: Specified directory does not exist: $1"
        exit 1
    fi
    INSTALL_DIRS=("$1")
else
    INSTALL_DIRS=("${FOUND_PATHS[@]}")
fi

SCRIPT_DIR="$(dirname "$0")"
TOC_FILE="$SCRIPT_DIR/ph/ph.toc"

# Extract version from .toc file
VERSION="unknown"
if [ -f "$TOC_FILE" ]; then
    VERSION=$(grep "^## Version:" "$TOC_FILE" | sed 's/^## Version: *//' | tr -d ' ')
fi

INSTALL_TIMESTAMP=$(date '+%Y-%m-%d %H:%M:%S %Z')

for ADDONS_DIR in "${INSTALL_DIRS[@]}"; do
TARGET_DIR="$ADDONS_DIR/pH"
echo "Installing to: $ADDONS_DIR"
echo "Version: $VERSION"
echo ""

# Remove existing installation if present
if [ -d "$TARGET_DIR" ]; then
    echo "Removing existing pH installation..."
    rm -rf "$TARGET_DIR"
fi

# Copy addon files
echo "Copying pH addon files..."
cp -r "$SCRIPT_DIR/ph" "$ADDONS_DIR/"

# Create installation info file
INSTALL_INFO_FILE="$TARGET_DIR/.install_info"
cat > "$INSTALL_INFO_FILE" << EOF
# pH Installation Information
# This file is automatically generated by the installer

Version: $VERSION
Installed: $INSTALL_TIMESTAMP
Installer: install.sh
EOF

# Verify installation
if [ -f "$TARGET_DIR/ph.toc" ]; then
    echo ""
    echo "✅ pH installed successfully!"
    echo ""
    echo "Installation details:"
    echo "  Version: $VERSION"
    echo "  Installed: $INSTALL_TIMESTAMP"
    echo "  Location: $TARGET_DIR"
    echo ""
    echo "Next steps:"
    echo "  1. Launch or /reload World of Warcraft"
    echo "  2. Type: /ph help"
    echo "  3. Start tracking: /ph start"
    echo ""
    echo "Testing without in-game actions:"
    echo "  /ph test run       - Run automated tests"
    echo "  /ph test loot 500  - Inject test gold"
    echo ""
else
    echo "❌ Installation may have failed. ph.toc not found."
    exit 1
fi
done
